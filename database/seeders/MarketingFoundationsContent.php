## الرقم الذي يحكم على كل شيء

المعرفة التسويقية بلا رقم تبقى فلسفة. لذلك تنتهي بطاقة القيمة بحساب بسيط يحمي ميزانيتك قبل أن تُنفق ريالاً واحداً: كم عميلاً تحتاج شهرياً؟

الحساب: **الإيراد الشهري المستهدف ÷ متوسط سعر العرض = عدد العملاء المطلوب**. إذا كان هدفك 20,000 ريال وسعر العرض 180 ريالاً فأنت تحتاج 112 عميلاً شهرياً. السؤال التالي فوراً: هل تستطيع خدمة 112 عميلاً شهرياً بطاقتك الحالية؟ هل تستطيع الوصول إليهم بميزانيتك؟ إن كانت طاقتك 60 عميلاً فالمشكلة ليست تسويقية بعد؛ المشكلة في السعر أو في هدف الإيراد. وإن كانت الميزانية لا تكفي للوصول إلى هذا العدد فالدرس الخامس سيقول لك ذلك بالأرقام قبل أن تكتشفه بالخسارة.

هذا الرقم سيظهر في كل درس تالٍ: الشريحة تُقاس بقدرتها على إنتاجه، الرسالة تُقاس باستجابتها نحوه، والقناة تُقاس بتكلفتها للوصول إليه.

## لماذا يفشل التسويق الذي يبدأ من المنتج

عندما تبدأ من المنتج تكتب عن المكونات والميزات والجوائز، ويقرأ العميل ولا يجد نفسه في النص. وعندما تبدأ من «الجميع» تضطر إلى رسالة عامة لا تلمس أحداً، وتدفع للوصول إلى آلاف لا يعانون من المشكلة أصلاً. وعندما لا يكون لديك رقم، تصبح كل حملة تجربة بلا حكم: لا تعرف إن كانت نجحت أم لا، فتُكررها أو توقفها بالإحساس.

بطاقة القيمة تعالج الثلاثة دفعة واحدة: مشكلة بدل منتج، شريحة بدل الجميع، ورقم بدل الإحساس.

## كيف تكتب البطاقة في عشر دقائق

اكتب كل إجابة بجملة واحدة بلغة يفهمها عميلك لو قرأها. تجنب الصفات (ممتاز، عالي الجودة، احترافي) واستبدلها بأشياء يمكن التحقق منها. إذا لم تعرف البديل الحالي لعملائك فاتصل بثلاثة ممن اشتروا منك واسألهم: «ماذا كنت تفعل قبل أن تجدنا؟». إجاباتهم أثمن من أي تحليل.

ثم اذهب إلى المختبر أدناه: الحقول مُعبّأة مسبقاً من ملف مشروعك حيث أمكن، وشريط «ماذا لو» سيُريك أثر تغيير السعر على عدد العملاء المطلوب مقارنة بطاقتك.

