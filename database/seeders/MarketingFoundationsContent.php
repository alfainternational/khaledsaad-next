القياس يفشل عندما يكثر. لوحة من عشرين رقماً لا يقرأها أحد. يكفيك مؤشران:

- **المؤشر القيادي** يتحرك أسبوعياً ويخبرك مبكراً إن كنت على الطريق: عدد المحادثات المؤهلة، عدد من أخذوا الخطوة التالية، تكلفة الطلب. هو المؤشر الذي تستطيع التأثير فيه هذا الأسبوع.
- **مؤشر النتيجة** هو ما تريده فعلاً: العملاء الجدد أو الإيراد. يتأخر عن القيادي بأسبوع أو أسبوعين، لذلك لا يصلح وحده للقرار الأسبوعي.

سجّل الاثنين في نهاية كل أسبوع في جدول من سطرين، مقابل **خط الأساس** (أرقام الأسبوع الذي سبق الخطة). بلا خط أساس لا تعرف إن كان الرقم تحسناً أم عادة.

## القرار الأسبوعي الثلاثي

ما يميّز الخطة الحية عن الميتة هو قرار مكتوب في نهاية كل أسبوع، من ثلاثة فقط:

1. **استمر**: المؤشر القيادي عند الهدف الأسبوعي أو فوقه. لا تغيّر شيئاً حتى لو خطرت لك فكرة جديدة؛ الاستقرار هو ما يسمح بالتعلم.
2. **عدّل جزءاً واحداً**: المؤشر القيادي بين 70٪ و100٪ من الهدف. غيّر عنصراً واحداً فقط (الرسالة أو الشريحة أو الميزانية أو الخطوة التالية) وسجّل ماذا غيّرت، لتعرف في الأسبوع التالي أثره.
3. **أوقف وأعد التشخيص**: المؤشر القيادي دون 70٪ لأسبوعين متتاليين. التوقف هنا ليس فشلاً بل توفير: الخلل غالباً في أصل سابق (الشريحة أو الرسالة) لا في التنفيذ، وإعادة التشخيص تُظهره.

## إيقاع الأسابيع الأربعة

- **الأسبوع 1 — التشغيل**: فعّل القناة الأولى بالرسالة الأساسية، سجّل خط الأساس، وافتح أول محادثات مؤهلة. لا تحكم على شيء هذا الأسبوع.
- **الأسبوع 2 — القراءة الأولى**: أول قياس حقيقي للمؤشر القيادي. قرار واحد من الثلاثة.
- **الأسبوع 3 — التثبيت أو التعديل**: إن استمررت، ثبّت كل شيء وركّز على الإغلاق (الخطوة التالية). إن عدّلت، قِس أثر التعديل الواحد.
- **الأسبوع 4 — الحكم**: قارن الأسبوع الرابع بخط الأساس. هذا هو «الأثر» الذي يُقاس: كم زاد المؤشر القيادي ومؤشر النتيجة؟ ثم أعد التشخيص لترى كيف تحركت أبعادك.

## الأثر الذي يُقاس

في نهاية الأسابيع الأربعة لديك ما لم يكن لديك في البداية: رقم حقيقي لتكلفة الطلب، معدل استجابة حقيقي لرسالتك، معدل تأهيل حقيقي لشريحتك، وقرار مبني على أرقام عن الخطوة التالية (توسّع، تعديل، أو قناة ثانية). هذا هو الفرق بين «جرّبنا التسويق ولم ينفع» و«عرفنا بالضبط ما نفع وبكم». المسار التالي (الجمهور والشخصيات) يبدأ من هذه الأرقام لا من الصفر.

