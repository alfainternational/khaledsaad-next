# أثر

منصة عربية للتسويق الرقمي والذكاء الاصطناعي، تجمع المحتوى الموثق والتعليم التطبيقي والأدوات.

## الأقسام
- /articles — المقالات والأدلة
- /insights — الرؤى العالمية المراجعة
- /academy — المسارات التعليمية
- /tools — مختبر التسويق
- /about — المنهجية وسياسة المصادر والتصحيح

## الاستخدام
استخدم الروابط القانونية العامة فقط. لا تفترض أن llms.txt يمنح حق إعادة نشر المحتوى. ارجع إلى المصادر الظاهرة في كل مادة.
