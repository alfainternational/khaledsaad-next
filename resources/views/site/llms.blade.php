# أثر

> منصة عربية لتعلّم التسويق الرقمي والذكاء الاصطناعي بالممارسة: تشخيص ← مسار ← درس ← مختبر ← أصل لمشروعك. كل مادة تحمل مؤلفاً وتاريخ مراجعة ومصادر، وكل أداة تعمل بلا تسجيل.

## ابدأ من هنا
- [شخّص مشروعك]({!! route('assess.start') !!}): تشخيص بثلاث مراحل ينتهي بخريطة أولويات ونقطة بداية
- [الأكاديمية]({!! route('academy.index') !!}): {!! $courses->count() !!} مساراً و{!! $courses->sum('lessons_count') !!} درساً، كل درس ينتهي بأصل قابل للحفظ
- [المختبر]({!! route('tools.index') !!}): مولدات وحاسبات ومحاكي حملة
- [الموارد]({!! route('resources') !!}): قوالب تطبيقية مرتبطة بالدروس، بمعاينة وتنزيل
- [قاموس التسويق]({!! route('glossary.index') !!}): تعريف مباشر في أول سطر، ثم مثال ومواد مرتبطة

