**تكلفة الطلب** (أو تكلفة المحادثة المؤهلة) هي ما تدفعه للحصول على طلب أو محادثة واحدة مؤهلة من القناة. لكل قناة في السوق السعودي معدلات مرجعية تقريبية للمشاريع الصغيرة، وهي افتراضات مُعلنة في هذا الدرس يمكنك تعديلها بأرقامك عندما تملكها: واتساب والبث المباشر لعملائك الحاليين أرخص القنوات (نحو 15 ريالاً)، التوصيات أرخص (نحو 10)، إنستغرام وسناب وتيك توك في نطاق 35–40 ريالاً للطلب في الاستهداف الجيد، بحث جوجل أغلى (نحو 70) لكنه يأتي بنية شراء أعلى، والميدان والمعارض الأغلى (نحو 90) لكنها تبني ثقة سريعة.

الحساب الذي يسبق الإنفاق: **الطلبات المتوقعة = الميزانية الشهرية ÷ تكلفة الطلب المرجعية**. بميزانية 3,000 ريال على إنستغرام بتكلفة مرجعية 40 ريالاً تتوقع نحو 75 طلباً. قارنه برقمك: إن كنت تحتاج 60 فأنت ضمن الهدف؛ إن كنت تحتاج 150 فأنت خارج الهدف قبل أن تنفق، وعليك إما رفع الميزانية أو خفض التكلفة (شريحة أدق ورسالة أفضل) أو اختيار قناة أرخص.

## ما الذي يخفّض تكلفة الطلب فعلاً

تكلفة الطلب ليست قدراً تفرضه المنصة؛ ثلاثة أشياء تحرّكها أكثر من أي إعداد تقني: دقة الشريحة (الدرس الثالث) لأنك لا تدفع للوصول إلى غير المهتمين، قوة الرسالة (الدرس الرابع) لأن معدل الاستجابة الأعلى يعني طلبات أكثر بالوصول نفسه، ووضوح الخطوة التالية لأن الطلب يُحسب فقط عندما يأخذها أحد. لذلك جاءت هذه الدروس قبل درس القناة: الإنفاق على شريحة غامضة برسالة ضعيفة يرفع التكلفة مهما ضبطت الإعدادات.

## الميزانية اليومية وفترة التعلم

قسّم الميزانية الشهرية على 30 يوماً تحصل على الميزانية اليومية. الحد الأدنى العملي لأغلب منصات الإعلان هو نحو 30–50 ريالاً يومياً حتى تجمع بيانات كافية؛ أقل من ذلك تبقى الحملة في «مرحلة التعلم» بلا نتائج مستقرة. إن كانت ميزانيتك أقل من 1,000 ريال شهرياً فالقناة الأولى المناسبة غالباً عضوية أو مباشرة (واتساب، توصيات، محتوى) لا مدفوعة.

## قاعدة القرار قبل أن تبدأ

أخطر ما في الإنفاق هو غياب قاعدة توقف أو مضاعفة. اكتبها الآن، قبل اليوم الأول:

- **تكلفة الطلب المقبولة**: الحد الذي يبقى معه الطلب مربحاً (عادة ≤ 30٪ من هامش ربح العميل الواحد).
- **موعد القرار**: بعد 14 يوماً من الإنفاق المستمر، لا قبل ذلك ولا بالإحساس.
- **القرار الثلاثي**: إن كانت التكلفة ≤ المقبولة ضاعف الميزانية تدريجياً (25٪ أسبوعياً)؛ إن كانت أعلى بأقل من 50٪ عدّل الرسالة أو الشريحة وأعد 14 يوماً؛ إن كانت أعلى بأكثر من 50٪ أوقف وغيّر القناة.

هذه القاعدة تحوّل الإعلان من مقامرة إلى تجربة مقيسة، وتجعل الإنفاق الصغير مفيداً حتى عندما يفشل، لأنه يعطيك رقماً.

## القناة الثانية: متى وكيف

لا تُضاف القناة الثانية لأن الأولى «مملة» أو لأن منافساً ظهر على منصة جديدة؛ تُضاف عندما تعرف تكلفة الطلب في القناة الأولى وتكون ضمن المقبول وتريد المزيد مما لا تستطيع الأولى إعطاءه. عندها تُعامل الثانية كتجربة جديدة بالقاعدة نفسها: 14 يوماً، تكلفة طلب مستهدفة، وقرار ثلاثي، بميزانية لا تُؤخذ من الأولى الناجحة.

