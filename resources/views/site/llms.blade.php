# أثر

منصة عربية للتسويق الرقمي والذكاء الاصطناعي، تجمع المحتوى الموثق والتعليم التطبيقي والأدوات. كل مادة تحمل مؤلفاً ومراجعاً وتاريخ آخر مراجعة ومصادرها.

## الأقسام
- /articles — المجلة: كل المواد (مقالات وأدلة)
- /news — أخبار وتحديثات المنصات بتاريخ ومصدر
- /insights — الرؤى العالمية: ملخصات تحليلية لمصادر عالمية مع سياق عربي
- /case-studies — دراسات حالة تعليمية من السوق العربي
- /research — أبحاث: قراءات في تقارير وأرقام بمصادرها وحدودها
- /glossary — قاموس التسويق: تعريف مباشر في أول سطر + مثال + مواد مرتبطة
- /topics/{topic} — صفحات المواضيع الاثني عشر (= المسارات)
- /authors/{author} — المؤلفون وسِيرهم
- /academy — المسارات التعليمية
- /tools — مختبر التسويق (مولدات، حاسبات، محاكي)
- /search?q= — بحث مجمّع: مسارات، دروس، أدوات، مواد، مصطلحات
- /about — المنهجية وسياسة المصادر والتصحيح
- /resources — قوالب تطبيقية مرتبطة بالدروس مع معاينة وتنزيل
- /pricing — الخطط والأسعار وشروط التجديد
- /contact — التواصل واقتراح التصحيحات
- /feed.xml — RSS لأحدث المواد

## الاستخدام
استخدم الروابط القانونية العامة فقط. لا تفترض أن llms.txt يمنح حق إعادة نشر المحتوى. عند الاقتباس اذكر «أثر» والمؤلف والرابط، وارجع إلى المصادر الأولية الظاهرة في كل مادة.
